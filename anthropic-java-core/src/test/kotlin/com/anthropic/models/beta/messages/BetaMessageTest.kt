package com.anthropic.models.beta.messages

import com.anthropic.core.jsonMapper
import com.anthropic.models.messages.Model
import com.fasterxml.jackson.module.kotlin.jacksonTypeRef
import java.time.OffsetDateTime
import kotlin.jvm.optionals.getOrNull
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test

internal class BetaMessageTest {

    @Test
    fun create() {
        val betaMessage =
            BetaMessage.builder()
                .id("msg_013Zva2CMHLNnXjNJJKqJ2EF")
                .container(
                    BetaContainer.builder()
                        .id("container_011CpZohnwH4vuy7gazohgSP")
                        .expiresAt(OffsetDateTime.parse("2019-12-27T18:11:19.117Z"))
                        .addSkill(
                            BetaContainerSkill.builder()
                                .skillId("pdf")
                                .type(BetaContainerSkill.Type.ANTHROPIC)
                                .version("latest")
                                .build()
                        )
                        .build()
                )
                .addContent(
                    BetaTextBlock.builder().citations(null).text("Hi! My name is Claude.").build()
                )
                .contextManagement(
                    BetaContextManagementResponse.builder()
                        .addAppliedEdit(
                            BetaClearToolUses20250919EditResponse.builder()
                                .clearedInputTokens(0L)
                                .clearedToolUses(0L)
                                .build()
                        )
                        .build()
                )
                .diagnostics(null)
                .model(Model.CLAUDE_OPUS_5_5)
                .stopDetails(null)
                .stopReason(BetaStopReason.END_TURN)
                .stopSequence(null)
                .usage(
                    BetaUsage.builder()
                        .cacheCreation(
                            BetaCacheCreation.builder()
                                .ephemeral1hInputTokens(0L)
                                .ephemeral5mInputTokens(0L)
                                .build()
                        )
                        .cacheCreationInputTokens(2051L)
                        .cacheReadInputTokens(2051L)
                        .fallbackCredit(
                            BetaFallbackCreditUsage.builder()
                                .status(BetaFallbackCreditRedeemed.builder().build())
                                .build()
                        )
                        .inferenceGeo("global")
                        .inputTokens(2095L)
                        .addIteration(
                            BetaMessageIterationUsage.builder()
                                .cacheCreation(
                                    BetaCacheCreation.builder()
                                        .ephemeral1hInputTokens(0L)
                                        .ephemeral5mInputTokens(0L)
                                        .build()
                                )
                                .cacheCreationInputTokens(0L)
                                .cacheReadInputTokens(0L)
                                .inputTokens(0L)
                                .model(Model.CLAUDE_FABLE_5_2)
                                .outputTokens(0L)
                                .build()
                        )
                        .outputTokens(503L)
                        .outputTokensDetails(BetaOutputTokensDetails.of(0L))
                        .serverToolUse(
                            BetaServerToolUsage.builder()
                                .webFetchRequests(2L)
                                .webSearchRequests(0L)
                                .build()
                        )
                        .serviceTier(BetaUsage.ServiceTier.STANDARD)
                        .speed(BetaUsage.Speed.STANDARD)
                        .build()
                )
                .addInputTransformation(
                    BetaThinkingDroppedInputTransformation.builder()
                        .path("path")
                        .reason(
                            BetaThinkingDroppedInputTransformation.Reason.MODEL_BINDING_MISMATCH
                        )
                        .build()
                )
                .build()

        assertThat(betaMessage.id()).isEqualTo("msg_013Zva2CMHLNnXjNJJKqJ2EF")
        assertThat(betaMessage.container())
            .contains(
                BetaContainer.builder()
                    .id("container_011CpZohnwH4vuy7gazohgSP")
                    .expiresAt(OffsetDateTime.parse("2019-12-27T18:11:19.117Z"))
                    .addSkill(
                        BetaContainerSkill.builder()
                            .skillId("pdf")
                            .type(BetaContainerSkill.Type.ANTHROPIC)
                            .version("latest")
                            .build()
                    )
                    .build()
            )
        assertThat(betaMessage.content())
            .containsExactly(
                BetaContentBlock.ofText(
                    BetaTextBlock.builder().citations(null).text("Hi! My name is Claude.").build()
                )
            )
        assertThat(betaMessage.contextManagement())
            .contains(
                BetaContextManagementResponse.builder()
                    .addAppliedEdit(
                        BetaClearToolUses20250919EditResponse.builder()
                            .clearedInputTokens(0L)
                            .clearedToolUses(0L)
                            .build()
                    )
                    .build()
            )
        assertThat(betaMessage.diagnostics()).isEmpty
        assertThat(betaMessage.model()).isEqualTo(Model.CLAUDE_OPUS_5_5)
        assertThat(betaMessage.stopDetails()).isEmpty
        assertThat(betaMessage.stopReason()).contains(BetaStopReason.END_TURN)
        assertThat(betaMessage.stopSequence()).isEmpty
        assertThat(betaMessage.usage())
            .isEqualTo(
                BetaUsage.builder()
                    .cacheCreation(
                        BetaCacheCreation.builder()
                            .ephemeral1hInputTokens(0L)
                            .ephemeral5mInputTokens(0L)
                            .build()
                    )
                    .cacheCreationInputTokens(2051L)
                    .cacheReadInputTokens(2051L)
                    .fallbackCredit(
                        BetaFallbackCreditUsage.builder()
                            .status(BetaFallbackCreditRedeemed.builder().build())
                            .build()
                    )
                    .inferenceGeo("global")
                    .inputTokens(2095L)
                    .addIteration(
                        BetaMessageIterationUsage.builder()
                            .cacheCreation(
                                BetaCacheCreation.builder()
                                    .ephemeral1hInputTokens(0L)
                                    .ephemeral5mInputTokens(0L)
                                    .build()
                            )
                            .cacheCreationInputTokens(0L)
                            .cacheReadInputTokens(0L)
                            .inputTokens(0L)
                            .model(Model.CLAUDE_FABLE_5_2)
                            .outputTokens(0L)
                            .build()
                    )
                    .outputTokens(503L)
                    .outputTokensDetails(BetaOutputTokensDetails.of(0L))
                    .serverToolUse(
                        BetaServerToolUsage.builder()
                            .webFetchRequests(2L)
                            .webSearchRequests(0L)
                            .build()
                    )
                    .serviceTier(BetaUsage.ServiceTier.STANDARD)
                    .speed(BetaUsage.Speed.STANDARD)
                    .build()
            )
        assertThat(betaMessage.inputTransformations().getOrNull())
            .containsExactly(
                BetaInputTransformation.ofThinkingDropped(
                    BetaThinkingDroppedInputTransformation.builder()
                        .path("path")
                        .reason(
                            BetaThinkingDroppedInputTransformation.Reason.MODEL_BINDING_MISMATCH
                        )
                        .build()
                )
            )
    }

